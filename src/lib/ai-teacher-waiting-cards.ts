export const AI_TEACHER_WAITING_CARDS: Record<AiTeacherSpace, WaitingCard[]> = {
  student: [...SHARED, ...STUDENT_ONLY],
  abiturient: [...SHARED, ...ABITURIENT_ONLY],
};

const SEEN_KEY = "spaceedu-ai-teacher-cards-seen";

function readSeen(): string[] {
  try {
    return JSON.parse(window.sessionStorage.getItem(SEEN_KEY) ?? "[]") as string[];
  } catch {
    return [];
  }
}

/**
 * The next card this session hasn't shown yet (random order). Once all
 * were seen, the cycle starts over.
 */
export function nextWaitingCard(space: AiTeacherSpace, random: () => number = Math.random): WaitingCard {
  const cards = AI_TEACHER_WAITING_CARDS[space];
  let seen = typeof window === "undefined" ? [] : readSeen();
  let fresh = cards.filter((card) => !seen.includes(card.id));
  if (fresh.length === 0) {
    seen = [];
    fresh = cards;
  }
  const card = fresh[Math.floor(random() * fresh.length)];
  try {
    window.sessionStorage.setItem(SEEN_KEY, JSON.stringify([...seen, card.id]));
  } catch {
    // no storage — repeats are possible, that's all
  }
  return card;
}

const LEARNED_KEY = "spaceedu-ai-teacher-tips-learned";

/** Today's date as YYYY-MM-DD in local time. */
function today(now: Date = new Date()): string {
  const pad = (n: number) => String(n).padStart(2, "0");
  return `${now.getFullYear()}-${pad(now.getMonth() + 1)}-${pad(now.getDate())}`;
}

/** How many tips the student flipped today (resets each day). */
export function readTipsLearnedToday(now: Date = new Date()): number {
  try {
    const stored = JSON.parse(window.localStorage.getItem(LEARNED_KEY) ?? "null") as { date: string; count: number } | null;
    return stored && stored.date === today(now) ? stored.count : 0;
  } catch {
    return 0;
  }
}

export function addTipLearnedToday(now: Date = new Date()): number {
  const count = readTipsLearnedToday(now) + 1;
  try {
    window.localStorage.setItem(LEARNED_KEY, JSON.stringify({ date: today(now), count }));
  } catch {
    // ignore
  }
  return count;
}
